# Wire types

class Buf:
    __slots__ = ("d", "i")

    def __init__(self, d, i=0):
        self.d = d
        self.i = i

    def remaining(self):
        return len(self.d) - self.i

    def take(self, n):
        j = self.i + n
        if n < 0 or j > len(self.d):
            raise DecodeError("truncated (need %d bytes at %d of %d)" % (n, self.i, len(self.d)))
        b = self.d[self.i:j]
        self.i = j
        return b

    def u8(self):
        if self.i >= len(self.d):
            raise DecodeError("truncated")
        b = self.d[self.i]
        self.i += 1
        return b

    def bool(self):
        return self.u8() != 0

    def _num(self, fmt, n):
        if self.i + n > len(self.d):
            raise DecodeError("truncated")
        v = struct.unpack_from(fmt, self.d, self.i)[0]
        self.i += n
        return v

    def i8(self):
        return self._num(">b", 1)

    def i16(self):
        return self._num(">h", 2)

    def u16(self):
        return self._num(">H", 2)

    def i32(self):
        return self._num(">i", 4)

    def i64(self):
        return self._num(">q", 8)

    def f32(self):
        return self._num(">f", 4)

    def f64(self):
        return self._num(">d", 8)

    def varint(self):
        v = shift = 0
        while True:
            b = self.u8()
            v |= (b & 0x7F) << shift
            if not b & 0x80:
                break
            shift += 7
            if shift > 28:
                raise DecodeError("VarInt too long")
        v &= 0xFFFFFFFF
        return v - (1 << 32) if v & 0x80000000 else v

    def varlong(self):
        v = shift = 0
        while True:
            b = self.u8()
            v |= (b & 0x7F) << shift
            if not b & 0x80:
                break
            shift += 7
            if shift > 63:
                raise DecodeError("VarLong too long")
        v &= 0xFFFFFFFFFFFFFFFF
        return v - (1 << 64) if v & (1 << 63) else v

    def uuid(self):
        h = self.take(16).hex()
        return "%s-%s-%s-%s-%s" % (h[:8], h[8:12], h[12:16], h[16:20], h[20:])

    def string(self):
        n = self.varint()
        if n < 0 or n > 1 << 21:
            raise DecodeError("bad string length %d" % n)
        return self.take(n).decode("utf-8", "replace")

    def position(self):
        v = self.i64()
        y = v & 0xFFF
        z = (v >> 12) & 0x3FFFFFF
        return v >> 38, y - 0x1000 if y >= 0x800 else y, z - 0x4000000 if z >= 0x2000000 else z

    def angle(self):
        return self.i8() * 360.0 / 256.0

    def nbt(self):
        """Network NBT (1.20.2+): tag type, then the payload; the root has no name."""
        t = self.u8()
        return None if t == 0 else nbt_payload(self, t)


def nbt_payload(b, t, depth=0):
    if depth > 512:
        raise DecodeError("NBT nested too deep")
    if t == 1:
        return b.i8()
    if t == 2:
        return b.i16()
    if t == 3:
        return b.i32()
    if t == 4:
        return b.i64()
    if t == 5:
        return b.f32()
    if t == 6:
        return b.f64()
    if t == 7:
        return b.take(b.i32())
    if t == 8:
        return b.take(b.u16()).decode("utf-8", "replace")
    if t == 9:
        et = b.u8()
        n = b.i32()
        return [nbt_payload(b, et, depth + 1) for _ in range(max(n, 0))]
    if t == 10:
        out = {}
        while True:
            et = b.u8()
            if et == 0:
                return out
            name = b.take(b.u16()).decode("utf-8", "replace")
            out[name] = nbt_payload(b, et, depth + 1)
    if t == 11:
        n = b.i32()
        return list(struct.unpack(">%di" % n, b.take(4 * n)))
    if t == 12:
        n = b.i32()
        return list(struct.unpack(">%dq" % n, b.take(8 * n)))
    raise DecodeError("bad NBT tag type %d" % t)


def read_nbt_file(path):
    """A named-root NBT file (structure .nbt), gzip or raw."""
    with open(path, "rb") as f:
        data = f.read()
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    b = Buf(data)
    if b.u8() != 10:
        raise DecodeError("%s: root is not a compound" % path)
    b.take(b.u16())
    return nbt_payload(b, 10)


_FMT_RE = re.compile(r"\{(\d+)\}|%(?:(\d+)\$)?[sd]|%%")


def translate(lang, key, args, fallback=None):
    fmt = lang.get(key) or fallback
    if fmt is None:
        return "%s(%s)" % (key, ", ".join(args)) if args else key
    seq = iter(range(len(args)))

    def sub(m):
        if m.group(0) == "%%":
            return "%"
        idx = m.group(1) or m.group(2)
        i = int(idx) - (1 if m.group(2) else 0) if idx else next(seq, None)
        return args[i] if i is not None and 0 <= i < len(args) else ""
    return _FMT_RE.sub(sub, fmt)


def component_text(c, lang):
    """Plain text of a chat component given as decoded NBT (string, compound or list)."""
    if c is None:
        return ""
    if isinstance(c, (str, int, float)):
        return str(c)
    if isinstance(c, list):
        return "".join(component_text(x, lang) for x in c)
    if not isinstance(c, dict):
        return ""
    if "text" in c:
        s = str(c["text"])
    elif "" in c:
        s = component_text(c[""], lang)
    elif "translate" in c:
        s = translate(lang, str(c["translate"]), [component_text(a, lang) for a in c.get("with", [])],
                      c.get("fallback"))
    elif "keybind" in c:
        s = str(c["keybind"])
    elif "selector" in c:
        s = str(c["selector"])
    elif "score" in c and isinstance(c["score"], dict):
        s = str(c["score"].get("value", ""))
    else:
        s = ""
    for e in c.get("extra", []) or []:
        s += component_text(e, lang)
    return s


