class Registry:
    def __init__(self, path=REGISTRY_FILE):
        with open(path) as f:
            r = json.load(f)
        if r.get("protocol") != PROTOCOL:
            raise SystemExit("%s is for protocol %s, not %d" % (path, r.get("protocol"), PROTOCOL))
        self.blocks = r["blocks"]
        self.by_name = {b[0]: b for b in self.blocks}
        self.state_block = [0] * (self.blocks[-1][2] + 1)
        for bi, (_name, lo, hi, _col) in enumerate(self.blocks):
            for s in range(lo, hi + 1):
                self.state_block[s] = bi
        self.items = r["items"]
        self.entities = r["entities"]
        self.map_colors = r["mapColors"]
        self.lang = r.get("lang", {})
        self.player_type = self.entities.index("player")

    def block_name(self, state):
        if state is None:
            return ""
        if 0 <= state < len(self.state_block):
            return self.blocks[self.state_block[state]][0]
        return "state#%d" % state

    def block_color(self, state):
        if state is None or not 0 <= state < len(self.state_block):
            return None
        return self.blocks[self.state_block[state]][3]

    def entity_name(self, t):
        return self.entities[t] if 0 <= t < len(self.entities) else "entity#%d" % t


