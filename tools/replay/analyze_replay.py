    # -- driver ------------------------------------------------------------------------------------------------
    def run(self, records):
        for t, payload in records:
            self.n_records += 1
            if self.n_records > 1:
                gap = t - self.last_t
                if gap > self.max_gap[0]:
                    self.max_gap = (gap, self.last_t)
                if gap >= 3000 and self.state == "GAME":
                    self.gaps.append((self.last_t, gap))
            self.t = t
            self.last_t = max(self.last_t, t)
            self.dispatch(payload)

    def dispatch(self, payload):
        b = Buf(payload)
        try:
            pid = b.varint()
        except DecodeError:
            self.errors["(empty record)"] += 1
            return
        state = self.state
        if state == "LOGIN" and pid not in (0x00, 0x02):
            self.resync("LOGIN record id 0x%02x is not login_finished" % pid, "CONFIGURATION")
            state = self.state
        if state == "CONFIGURATION" and (pid not in CONFIG_NAMES or
                                         (self.config_tentative and not self.looks_like_config(pid, payload, b.i))):
            self.resync("id 0x%02x after start_configuration is a GAME packet" % pid if self.config_tentative
                        else "id 0x%02x is not a CONFIGURATION packet" % pid, "GAME")
            state = self.state
        self.config_tentative = False
        name = self.names[state].get(pid, "unknown_0x%02x" % pid)
        self.counts[(state, name)] += 1
        h = self._handlers[state].get(pid)
        if h is None:
            return
        try:
            h(b)
        except (DecodeError, struct.error, IndexError, ValueError, KeyError, TypeError) as e:
            self.errors[name] += 1
            self.error_samples.setdefault(name, "t=%d: %s" % (self.t, e))

    def resync(self, why, state):
        self.state_resyncs.append((self.t, why))
        self.state = state

    @staticmethod
    def looks_like_config(pid, payload, i):
        if pid == 0x03:
            return len(payload) == i
        if pid in (0x01, 0x07, 0x0C, 0x0D, 0x0E):
            b = Buf(payload, i)
            try:
                if pid != 0x01 and pid != 0x07:
                    if b.varint() > 4096:
                        return False
                return ":" in b.string() or pid == 0x0E
            except DecodeError:
                return False
        return pid in (0x04, 0x05) and len(payload) - i in (4, 8)

