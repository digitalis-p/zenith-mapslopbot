class ArtLayer:
    def __init__(self, min_x, min_z, art_y, dimension="minecraft:overworld", source="site", platform_id="",
                 watch=None):
        self.min_x, self.min_z, self.art_y = min_x, min_z, art_y
        self.dimension = dimension
        self.source = source
        self.platform_id = platform_id
        # (x, y, z) -> (label, kind): site blocks whose changes the report lists (buttons, note blocks, lamp...)
        self.watch = watch or {}

    def contains(self, x, z):
        return self.min_x <= x < self.min_x + TILE and self.min_z <= z < self.min_z + TILE

    @property
    def offset(self):
        return self.min_x + 64, self.min_z + 64


def lane_half_width_of(build):
    """The plugin's lane half width (PlaceMode.laneHalfWidth): AIRPLACE uses build.airPlaceLaneHalfWidth, -1 = the
    widest L with L^2 + 1.12^2 + 1 <= (airPlaceRange - 0.3)^2 (4 at 5.0); LOOK uses build.laneHalfWidth. A config
    without placeMode predates placement modes: LOOK. None if nothing usable is set."""
    mode = str(build.get("placeMode", "LOOK")).strip().upper()
    if mode in ("AIRPLACE", "AIR_PLACE", "AIR"):
        w = build.get("airPlaceLaneHalfWidth", -1)
        if isinstance(w, int) and w >= 0:
            return w
        rng = build.get("airPlaceRange", 5.0)
        r = (rng if isinstance(rng, (int, float)) else 5.0) - 0.3
        l2 = r * r - 1.12 * 1.12 - 1.0
        return 0 if l2 < 0 else int(math.floor(math.sqrt(l2) + 1e-9))
    w = build.get("laneHalfWidth")
    return w if isinstance(w, int) else None


def load_site(path, platform):
    """Returns (ArtLayer, laneHalfWidth or None). Accepts mapart.json (uses only "site" and build.laneHalfWidth)."""
    with open(path) as f:
        doc = json.load(f)
    site = doc.get("site", doc) if isinstance(doc, dict) else None
    if not isinstance(site, dict) or not isinstance(site.get("platforms"), list):
        raise SystemExit("%s: no site.platforms" % path)
    plats = [p for p in site["platforms"] if isinstance(p, dict)]
    if platform:
        want = platform.lower()
        plats = [p for p in plats if str(p.get("id", "")).lower() == want or str(p.get("kind", "")).lower() == want]
        if not plats:
            raise SystemExit("%s: no platform %r" % (path, platform))
    else:
        plats = [p for p in plats if p.get("enabled", True)] or plats
    if not plats:
        raise SystemExit("%s: no platforms" % path)
    p = plats[0]
    build = doc.get("build") if isinstance(doc, dict) else None
    lane = lane_half_width_of(build) if isinstance(build, dict) else None
    watch = {}

    def add(pos, label, kind):
        if isinstance(pos, dict) and all(isinstance(pos.get(k), int) for k in "xyz"):
            watch.setdefault((pos["x"], pos["y"], pos["z"]), (label, kind))
    for i, c in enumerate(p.get("clear") or []):
        if isinstance(c, dict):
            add(c.get("pos"), "clear button %d" % (i + 1), "clear")
            add(c.get("probe"), "clear %d side probe (%s)" % (i + 1, str(c.get("probeBlock", "")).split(":")[-1]),
                "probe")
    for key, label in (("collectionOn", "carts ON note block"), ("collectionOff", "carts OFF note block")):
        if isinstance(p.get(key), dict):
            add(p[key].get("pos"), label, "carts")
    add(p.get("collectionIndicator"), "carts lamp", "carts")
    for d in site.get("_doNotPress") or site.get("doNotPress") or []:
        if isinstance(d, dict):
            add(d, "DO NOT PRESS: %s" % d.get("why", ""), "forbidden")
    layer = ArtLayer(int(p["minX"]), int(p["minZ"]), int(p["artY"]), site.get("dimension") or "minecraft:overworld",
                     "site config %s, platform %s" % (os.path.basename(path), p.get("id", "?")), str(p.get("id", "")),
                     watch)
    return layer, lane


def load_plan(path, tile):
    """Expected art (block name or None per pixel, index pz*128+px) of tile (tx, tz) of a flat structure .nbt."""
    root = read_nbt_file(path)
    palette = root.get("palette")
    if palette is None and root.get("palettes"):
        palette = root["palettes"][0]
    if palette is None or "blocks" not in root or "size" not in root:
        raise SystemExit("%s is not a structure .nbt" % path)
    names = [str(p.get("Name", "minecraft:air")).split(":", 1)[-1] for p in palette]
    top = {}
    for blk in root["blocks"]:
        x, y, z = blk["pos"]
        cur = top.get((x, z))
        if cur is None or y >= cur[0]:
            top[(x, z)] = (y, blk["state"])
    sx, _sy, sz = root["size"]
    tx, tz = tile
    x0, z0 = tx * TILE, tz * TILE
    if x0 + TILE > sx or z0 + TILE + 1 > sz:
        raise SystemExit("%s: size %dx%d has no tile %d,%d" % (path, sx, sz, tx, tz))
    plan = [None] * (TILE * TILE)
    for pz in range(TILE):
        for px in range(TILE):
            v = top.get((x0 + px, z0 + pz + 1))
            if v is not None and names[v[1]] not in AIR:
                plan[pz * TILE + px] = names[v[1]]
    return plan


