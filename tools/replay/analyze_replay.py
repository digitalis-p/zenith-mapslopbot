class _Inflate(io.RawIOBase):
    """Raw-deflate reader for a zip entry whose central directory is missing (recording cut short)."""

    def __init__(self, f, method):
        self.f = f
        self.z = zlib.decompressobj(-15) if method == 8 else None
        self.buf = b""
        self.eof = False
        self.error = None

    def readable(self):
        return True

    def read(self, n=-1):
        while (n < 0 or len(self.buf) < n) and not self.eof:
            chunk = self.f.read(1 << 16)
            if not chunk:
                self.eof = True
                if self.z:
                    try:
                        self.buf += self.z.flush()
                    except zlib.error as e:
                        self.error = str(e)
                break
            if self.z is None:
                self.buf += chunk
                continue
            try:
                self.buf += self.z.decompress(chunk)
            except zlib.error as e:
                self.error = str(e)
                self.eof = True
            if self.z.eof:
                self.eof = True
        if n < 0:
            out, self.buf = self.buf, b""
        else:
            out, self.buf = self.buf[:n], self.buf[n:]
        return out


class Recording:
    def __init__(self, path):
        self.path = path
        self.meta = {}
        self.notes = []
        self.complete = True
        self.truncated_tail = False
        self._zip = None
        self.is_zip = True
        try:
            with zipfile.ZipFile(path) as z:
                names = z.namelist()
                if "recording.tmcpr" not in names:
                    raise SystemExit("%s has no recording.tmcpr" % path)
                if "metaData.json" in names:
                    self.meta = json.loads(z.read("metaData.json").decode("utf-8"))
                else:
                    self.complete = False
                    self.notes.append("metaData.json missing: the recording was not closed cleanly")
        except zipfile.BadZipFile:
            self.is_zip = False
            self.complete = False
            self.notes.append("zip directory missing (proxy killed or disk full?): read the raw entry as far as "
                              "it goes; no metaData.json")
        if not self.meta.get("date"):
            m = re.match(r"(\d{4}-\d\d-\d\d_\d\d-\d\d-\d\d)", os.path.basename(path))
            if m:
                dt = datetime.datetime.strptime(m.group(1), "%Y-%m-%d_%H-%M-%S")
                self.meta.setdefault("date", int(dt.timestamp() * 1000))
                self.notes.append("start time taken from the file name (second precision)")

    def _stream(self):
        if self.is_zip:
            self._zip = zipfile.ZipFile(self.path)
            return self._zip.open("recording.tmcpr")
        f = open(self.path, "rb")
        hdr = f.read(30)
        if len(hdr) < 30 or hdr[:4] != b"PK\x03\x04":
            raise SystemExit("%s is not a zip file" % self.path)
        method = struct.unpack("<H", hdr[8:10])[0]
        nlen, xlen = struct.unpack("<HH", hdr[26:30])
        name = f.read(nlen).decode("utf-8", "replace")
        f.read(xlen)
        if name != "recording.tmcpr" or method not in (0, 8):
            raise SystemExit("%s: first zip entry is %s (method %d), cannot recover" % (self.path, name, method))
        self._raw = _Inflate(f, method)
        return self._raw

    def records(self):
        s = self._stream()
        try:
            while True:
                h = _read_exact(s, 8)
                if len(h) < 8:
                    if h:
                        self.truncated_tail = True
                    break
                t, n = struct.unpack(">ii", h)
                if n < 0 or n > 1 << 26:
                    self.truncated_tail = True
                    self.notes.append("bad record length %d at t=%d: stopped there" % (n, t))
                    break
                p = _read_exact(s, n)
                if len(p) < n:
                    self.truncated_tail = True
                    break
                yield t, p
        finally:
            s.close()
            if self.is_zip:
                self._zip.close()
            else:
                self._raw.f.close()
        raw = getattr(self, "_raw", None)
        if raw is not None and raw.error:
            self.notes.append("deflate stream ends with an error (%s): last records lost" % raw.error)
        if self.truncated_tail:
            self.notes.append("last record is incomplete (cut off)")


def _read_exact(s, n):
    out = b""
    while len(out) < n:
        b = s.read(n - len(out))
        if not b:
            break
        out += b
    return out


