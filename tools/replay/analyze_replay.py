def support_resends(changes):
    """Indexes of changes that are the server re-sending the clicked block under a placement: a change at
    (x, y, z) with another change at (x, y+1, z) within 100 ms. Vanilla answers use_item_on with a block_update for
    both the clicked and the placed position, so every carpet placed on the floor also "changes" the floor block."""
    by_pos = collections.defaultdict(list)
    for t, x, y, z, _o, _n in changes:
        by_pos[(x, y, z)].append(t)
    out = set()
    for i, (t, x, y, z, _o, _n) in enumerate(changes):
        if any(abs(t2 - t) <= 100 for t2 in by_pos.get((x, y + 1, z), ())):
            out.add(i)
    return out


CLICK_RUN_GAP_MS = 3000
CLICK_RUN_MIN = 5
PAIR_MS = 5
STACK_WINDOW_MS = 400
AIR_NAMES = AIR


def quantile(values, q):
    """Nearest-rank quantile (0..1) of a list of numbers; None if empty."""
    if not values:
        return None
    v = sorted(values)
    return v[max(0, min(len(v) - 1, int(math.ceil(q * len(v))) - 1))]


def click_answers(events, art_y):
    """Server answers to use_item_on, in record order. Vanilla handleUseItemOn sends a block_update of the clicked
    block and one of the block on the clicked face's side, then the ack at the end of the tick. A LOOK click hits the
    floor block under the cell (art_y - 1, face UP): its answer is the floor and the cell (art_y). An AIRPLACE click
    hits the cell itself (face UP, cursor inside it): its answer is the cell and the cell above it (art_y + 1). Either
    pair has the same x/z, within PAIR_MS of each other, no ack between them. The cell's own block_update that the
    chunk's change broadcast sends after a placement is not an answer. Returns {event index of the second: answer},
    answer["kind"] "look" or "airplace"."""
    side = {art_y - 1: "look", art_y + 1: "airplace"}
    out = {}
    used = set()
    for i, e in enumerate(events):
        if e[0] != "bu" or i in used:
            continue
        for j in range(i + 1, min(len(events), i + 8)):
            f = events[j]
            if f[0] == "ack":
                break
            if f[0] != "bu" or j in used or f[2] != e[2] or f[4] != e[4] or f[1] - e[1] > PAIR_MS:
                continue
            top, other = (e, f) if e[3] == art_y else (f, e)
            if top[3] != art_y or other[3] not in side:
                continue
            used.update((i, j))
            out[j] = {"t": f[1], "x": top[2], "z": top[4], "state": top[5], "old": top[6], "kind": side[other[3]]}
            break
    return out


def click_analysis(an, run_gap_ms=CLICK_RUN_GAP_MS, min_run=CLICK_RUN_MIN, stack_ms=STACK_WINDOW_MS):
    """Pairs the bot's clicks with the server's answers (docs/ARCHITECTURE.md "Placement engine", PlaceTracker).

    Clicks are the recorder's swings of the bot (one per use_item_on while placing, LOOK or AIRPLACE: the recorder
    writes the offhand swing as a main-arm one). Runs: swings less than run_gap_ms apart, at least min_run of them
    (a lane, or one stand spot's clicks); a run with fewer than half of its clicks answered on the art layer is not
    placing (chests, breaking) and is left out. Each click takes the next block prediction sequence. A run's first
    sequence is the lowest one that no ack had covered before any of its clicks was sent (exact when the sequences
    before the run were all acked first: runs are seconds apart). The acks then give each click's round trip.
    Answers (click_answers: LOOK floor + cell, AIRPLACE cell + cell above) between two acks S' < S belong to S'+1..S
    in order (when there are as many). Outcomes: placed, rejected (the server answered with the old, empty cell),
    unchanged (the cell already held that block), acked without an answer, no ack. A rejection is at a stack end
    when a hotbar slot update showed a count of 0 within stack_ms before the click and stack_ms after its answer.
    """
    L = an.layer
    ev = an.click_events
    if L is None or not ev:
        return None
    answers = click_answers(ev, L.art_y)
    # answers per sequence, batch by batch
    ans_by_seq = {}
    mismatched = []
    pending = []
    last = None
    for i, e in enumerate(ev):
        if i in answers:
            pending.append(answers[i])
        elif e[0] == "ack":
            s = e[2]
            if last is None or s > last:
                n = s - last if last is not None else len(pending)
                if len(pending) == n:
                    for k, a in zip(range(s - n + 1, s + 1), pending):
                        ans_by_seq[k] = a
                elif pending:
                    mismatched.append((e[1], (last + 1 if last is not None else None), s, len(pending)))
                last = s
            pending = []
    acks = [(e[1], e[2]) for e in ev if e[0] == "ack"]
    zeros = [e[1] for e in ev if e[0] == "slot" and e[3] == 0]
    resyncs = [e[1] for e in ev if e[0] == "resync"]
    swings = [e[1] for e in ev if e[0] == "swing"]
    runs = []
    cur = []
    for t in swings:
        if cur and t - cur[-1] > run_gap_ms:
            runs.append(cur)
            cur = []
        cur.append(t)
    if cur:
        runs.append(cur)
    runs = [r for r in runs if len(r) >= min_run]
    lane_of = lambda x: (x - L.min_x) // an.lane_w
    ack_t_list = [t for t, _q in acks]
    ack_max = []  # highest sequence acked up to each ack
    for _t, q in acks:
        ack_max.append(max(q, ack_max[-1]) if ack_max else q)

    def acked_before(t):
        k = bisect.bisect_left(ack_t_list, t)
        return ack_max[k - 1] if k > 0 else -1

    rows = []
    run_info = []
    other_runs = 0
    for r in runs:
        seq0 = max(acked_before(t) + 1 - i for i, t in enumerate(r))
        mapped = []
        j = bisect.bisect_left(ack_t_list, r[0])
        for i, t in enumerate(r):
            q = seq0 + i
            while j < len(acks) and acks[j][1] < q:
                j += 1
            mapped.append((t, q, acks[j][0] if j < len(acks) else None, ans_by_seq.get(q)))
        if 2 * sum(1 for m in mapped if m[3] is not None) < len(mapped):
            other_runs += 1
            continue
        ri = len(run_info) + 1
        info = {"run": ri, "start": r[0], "end": r[-1], "clicks": len(r), "seq0": seq0}
        run_info.append(info)
        for t, q, ack_t, a in mapped:
            a = ans_by_seq.get(q)
            if a is None:
                outcome = "no ack" if ack_t is None else "acked, no answer"
            elif a["state"] is not None and an.reg.block_name(a["state"]) in AIR_NAMES:
                outcome = "rejected"
            elif a["old"] == a["state"]:
                outcome = "unchanged"
            else:
                outcome = "placed"
            stack_out = False
            if outcome == "rejected":
                hi = a["t"] + stack_ms
                stack_out = any(t - stack_ms <= z <= hi for z in zeros)
            rows.append({"run": ri, "t": t, "seq": q, "ack_t": ack_t, "answer": a, "outcome": outcome,
                         "stack_out": stack_out, "lane": lane_of(a["x"]) if a is not None else None})
    # per run and per lane
    for info in run_info:
        rr = [c for c in rows if c["run"] == info["run"]]
        rtt = [c["ack_t"] - c["t"] for c in rr if c["ack_t"] is not None]
        oc = collections.Counter(c["outcome"] for c in rr)
        lanes = collections.Counter(c.get("lane") for c in rr if c.get("lane") is not None)
        info.update({"outcomes": oc, "rtt": rtt, "stack_out": sum(c["stack_out"] for c in rr),
                     "lanes": sorted(lanes)})
    by_lane = collections.OrderedDict()
    for c in rows:
        if c.get("lane") is None:
            continue
        d = by_lane.setdefault(c["lane"], collections.Counter())
        d["clicks"] += 1
        d[c["outcome"]] += 1
        d["stack_out"] += c["stack_out"]
    rtt = [c["ack_t"] - c["t"] for c in rows if c["ack_t"] is not None]
    ans_ms = [c["answer"]["t"] - c["t"] for c in rows if c["answer"] is not None]
    return {"runs": run_info, "clicks": rows, "by_lane": by_lane, "rtt": rtt, "answer_ms": ans_ms,
            "outcomes": collections.Counter(c["outcome"] for c in rows), "swings": len(swings),
            "kinds": collections.Counter(c["answer"]["kind"] for c in rows if c["answer"] is not None),
            "stack_out": sum(c["stack_out"] for c in rows), "mismatched": mismatched, "resyncs": len(resyncs),
            "acks": len(acks), "other_runs": other_runs}


def detect_art_layer(an):
    """Y level and map tile with the most placed (non-air, non-machine) blocks."""
    tiles = collections.Counter()
    skip = support_resends(an.other_changes)
    for i, (_t, x, y, z, old, new) in enumerate(an.other_changes):
        if i not in skip and an.is_art(new) and not an.is_art(old):
            tiles[(y, (x + 64) // TILE, (z + 64) // TILE)] += 1
    if not tiles:
        return None
    (y, tx, tz), n = tiles.most_common(1)[0]
    return ArtLayer(tx * TILE - 64, tz * TILE - 64, y, an.dimension or "minecraft:overworld",
                    "auto-detected (%d placements at y%d in this map tile)" % (n, y))


def grid_at(an, event_index):
    """Art-layer grid just after art_events[event_index] (undo the later events from the final grid)."""
    g = list(an.grid)
    for t, idx, old, new, kind, source in reversed(an.art_events[event_index + 1:]):
        g[idx] = old
    return g


class Clock:
    def __init__(self, date_ms):
        self.date_ms = date_ms

    def wall(self, t):
        if not self.date_ms:
            return ""
        return datetime.datetime.fromtimestamp((self.date_ms + t) / 1000.0).strftime("%H:%M:%S.%f")[:-3]

    @staticmethod
    def rel(t):
        s = t / 1000.0
        return "%d:%06.3f" % (int(s // 60), s % 60)

    def both(self, t):
        w = self.wall(t)
        return "%s (+%s)" % (w, self.rel(t)) if w else "+" + self.rel(t)


class Coords:
    def __init__(self, offset=None):
        self.offset = offset

    def text(self, s):
        """Free text: in relative mode, mask numbers within 5000 of the base's real X or Z."""
        if not self.offset or not s:
            return s

        def sub(m):
            try:
                v = float(m.group(0).replace(",", ""))
            except ValueError:
                return m.group(0)
            return "<coord>" if any(abs(abs(v) - abs(o)) <= 5000 for o in self.offset if abs(o) > 5000) \
                else m.group(0)
        return re.sub(r"-?\d[\d,]*(\.\d+)?", sub, s)

    def xyz(self, p, prec=2):
        if p is None:
            return ""
        x, y, z = p
        if self.offset:
            x, z = x - self.offset[0], z - self.offset[1]
        if isinstance(x, float) or isinstance(z, float) or isinstance(y, float):
            return "%.*f %.*f %.*f" % (prec, x, prec, y, prec, z)
        return "%d %d %d" % (x, y, z)

    def x(self, v):
        return v - self.offset[0] if self.offset else v

    def z(self, v):
        return v - self.offset[1] if self.offset else v


def write_png(path, width, height, pixel, scale=4):
    rows = []
    for y in range(height):
        row = bytearray()
        for x in range(width):
            row += bytes(pixel(x, y)) * scale
        rows.extend([b"\x00" + bytes(row)] * scale)
    raw = b"".join(rows)

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width * scale, height * scale, 8, 2,
                                                                     0, 0, 0))
                + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def state_rgb(reg, state):
    if state is None:
        return (255, 0, 255)
    col = reg.block_color(state)
    if not col:
        return (32, 32, 32)
    rgb = reg.map_colors[col] if col < len(reg.map_colors) else 0
    return tuple(((rgb >> s) & 0xFF) * 220 // 255 for s in (16, 8, 0))  # flat-map shade


