#!/usr/bin/env python3
"""Analyse a ZenithProxy replay recording (.mcpr) of a map-art build. Python 3 stdlib only; run with -I.

Usage:
  python3 -I tools/replay/analyze_replay.py REPLAY.mcpr [--site SITE.json] [--platform ID]
          [--plan ART.nbt [--tile TX,TZ]] [--out DIR] [--relative] [--lane-half-width N] [--no-png]

  REPLAY.mcpr   ZenithProxy `replay` recording (run/replays/*.mcpr). A recording cut short by a killed proxy
                (zip without directory or metaData.json) is read as far as it goes.
  --site FILE   site config: the plugin's mapart.json (only its "site" object and the build lane width keys are read)
                or a bare site object such as testserver/local/site-config.moss.json. Gives the art layer
                (platform minX/minZ/artY), the dimension and the site blocks to watch (clear buttons and side
                probes, cart note blocks and lamp, _doNotPress). Without it the art layer is auto-detected: the
                Y level and 128x128 map tile with the most placed blocks.
  --platform ID platform id or kind (default: the first enabled platform).
  --plan FILE   MapArtCraft .nbt to compare the art layer against (flat art: topmost block per column,
                row z=0 is the noobline), tile TX,TZ of it (default 0,0).
  --out DIR     output directory (default: <replay name>-analysis next to the replay).
  --relative    print base-relative coordinates: real minus (minX+64, minZ+64) of the platform. Default:
                real coordinates (the report stays local; never commit it).
  --lane-half-width N  lane geometry of the plugin's serpentine planner: lane k covers pixel columns
                k*(2N+1) .. k*(2N+1)+2N. Default: from the site file's build section (placeMode AIRPLACE:
                airPlaceLaneHalfWidth, -1 = 4 at airPlaceRange 5; LOOK or no placeMode: laneHalfWidth), else 2.

Outputs in DIR: report.md, placements.csv (art-layer changes), clicks.csv (the bot's clicks: block prediction
sequence, ack round trip, the server's answer and its kind LOOK/AIRPLACE, outcome), setbacks.csv, chat.csv,
health.csv, containers.csv, players.csv, rate_10s.csv, lanes.csv, positions.csv (bot track), block_changes.csv
(other blocks), art-peak.png / art-final.png (art layer at its fullest and at the end) and art-diff.png (with --plan).

Format (ZenithProxy 3.7.2 feature/replay/ReplayRecording.java): a zip with recording.tmcpr and
metaData.json. recording.tmcpr is a sequence of records: int32 BE time in ms since the recording started,
int32 BE length, then one clientbound packet (VarInt packet id + body, uncompressed). Record 0 (time 0) is
LOGIN login_finished, then CONFIGURATION packets (registries, tags, brand) up to finish_configuration, then
GAME packets. Packets are 1.21.4 (protocol 769) whatever the server runs. Besides the server's packets the
recorder writes synthetic ones for the recording player: add_entity / set_entity_data at spawn, and on each
outgoing move a teleport_entity + rotate_head for the bot's own entity id (that is the bot's position track),
set_equipment on container clicks/closes and block actions, animate on swings. Serverbound packets are not
recorded.

Block names come from data/registry-1.21.4.json, generated by gen_registry.py from ZenithProxy's own
1.21.4 block registry (mcdata/blocks.smile in its jar): the same state ids the proxy decodes.
"""
