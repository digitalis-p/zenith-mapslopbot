    def on_block_event(self, b):
        pos = b.position()
        action = b.u8()
        param = b.u8()
        block_id = b.varint()
        name = self.reg.blocks[block_id][0] if 0 <= block_id < len(self.reg.blocks) else ""
        if action != 1 or not (name in CHEST_LIKE or name.endswith("shulker_box")):
            return
        if param > 0:
            for c in reversed(self.containers):
                if c["pos"] is None and c["t_close"] is None and abs(self.t - c["t_open"]) <= 1500:
                    c["pos"] = pos
                    c["block"] = name
                    break
        else:
            for c in reversed(self.containers):
                if c["pos"] == pos and c["t_close"] is None:
                    c["t_close"], c["close_how"] = self.t, "chest lid closed (block_event)"
                    if c is self.open_container:
                        self.open_container = None
                    break
                if c["pos"] == pos and c["close_how"].startswith("estimated") and self.t - c["t_close"] < 3000:
                    c["t_close"], c["close_how"] = self.t, "chest lid closed (block_event)"
                    break

