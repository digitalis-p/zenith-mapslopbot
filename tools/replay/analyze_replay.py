def analyse(path, site=None, platform=None, plan_path=None, tile=(0, 0), lane_half_width=None,
            registry=None, setback_burst=(5, 2000)):
    """Runs the analysis; returns (Analyzer, Recording, info dict). Two passes when the art layer is auto-detected."""
    reg = registry or Registry()
    layer, lane_cfg = (None, None)
    if site:
        layer, lane_cfg = load_site(site, platform)
    lw = lane_half_width if lane_half_width is not None else (lane_cfg if lane_cfg is not None else 2)
    plan = load_plan(plan_path, tile) if plan_path else None
    info = {"lane_half_width": lw}
    if layer is None:
        rec0 = Recording(path)
        probe = Analyzer(reg, None, lw, setback_burst)
        probe.run(rec0.records())
        layer = detect_art_layer(probe)
    rec = Recording(path)
    an = Analyzer(reg, layer, lw, setback_burst)
    if plan is not None:
        an.set_plan(plan)
    an.run(rec.records())
    return an, rec, info


