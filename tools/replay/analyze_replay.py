    def _move_player(self, eid, pos=None, delta=None):
        p = self.players.get(eid)
        if p is None or not p["alive"]:
            return
        if delta is not None and p["pos"] is not None:
            pos = (p["pos"][0] + delta[0], p["pos"][1] + delta[1], p["pos"][2] + delta[2])
        if pos is not None:
            p["pos"] = pos
            p["last_t"] = self.t
            self.player_distance(p)

